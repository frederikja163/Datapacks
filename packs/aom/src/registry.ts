//
// Buildings, jobs and resources are declared once here. The build emits
// specialized functions per building type (hire/generation/render, sign
// text); nothing interprets jobs at runtime.
//
// Recipe ids are validated against the generated vanilla recipe list at
// module load, so a typo fails `bun run typecheck`/`bun run build` instead of
// silently producing an unlock that grants nothing.
// ---------------------------------------------------------------------------

const RECIPE_IDS = new Set<string>(RECIPES);

const GATED_RECIPES: string[] = [];

/** Marks a vanilla recipe id as gated and returns it. */
function r(id: string): string {
  GATED_RECIPES.push(id);
  return id;
}

function rList(...ids: string[]): string[] {
  return ids.map(r);
}

/** A plan recipe id (generated by this pack, not a vanilla recipe). */
export function planRecipe(id: string, wood: string): string {
  return `aom:plan/${id}/${wood}`;
}

