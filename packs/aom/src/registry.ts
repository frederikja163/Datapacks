/** First `aom.action` index used by a building's storage buttons. */
function actionBase(type: BuildingType): number {
  return type.jobs.length + (type.population ? 2 : 0) + 1;
}

/** `aom.action` index of the population Add/Remove villager buttons. */
export function populationAction(
  type: BuildingType,
  kind: "add" | "remove",
): number {
  return type.jobs.length + (kind === "add" ? 1 : 2);
}

/** `aom.action` index for a deposit/withdraw button. */
export function storageAction(
  type: BuildingType,
  resourceIndex: number,
  kind: "deposit" | "withdraw",
  amountIndex: number,
): number {
  const base = actionBase(type);
  return base + resourceIndex * (STORAGE_AMOUNTS.length * 2) +
    (kind === "deposit" ? 0 : STORAGE_AMOUNTS.length) + amountIndex;
}

/** `aom.action` index of the delete-building button. */
export function deleteAction(type: BuildingType): number {
  return actionBase(type) +
    buildingResources(type).length * STORAGE_AMOUNTS.length * 2;
}

