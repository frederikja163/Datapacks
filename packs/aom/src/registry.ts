export interface TableEntry {
  /** Omitted for a "nothing" roll. */
  readonly resource?: string;
  readonly weight: number;
}

export type JobKind = "unlock" | "generation" | "storage" | "mechanic";

export interface Job {
  readonly id: string;
  readonly label: string;
  readonly kind: JobKind;
  /** Simple generation target. */
  readonly resource?: string;
  /** Weighted-generation table (mutually exclusive with `resource`). */
  readonly table?: readonly TableEntry[];
  /** Generation interval in minutes (1, 2, 5, 10 or 20; default 1). */
  readonly interval?: number;
  /** Storage capacity added per worker (default 576). */
  readonly capacity?: number;
  /** Unlock id this job activates. */
  readonly unlock?: string;
  /** Recipes a staffed unlock job grants. */
  readonly recipes?: readonly string[];
  /** Workers needed for an unlock to activate (default 1). */
  readonly required?: number;
  /** Special mechanic id. */
  readonly mechanic?: "leveller" | "portal" | "noop";
}

export type Category =
  | "Civic"
  | "Extraction"
  | "Industry"
  | "Agriculture"
  | "Husbandry"
  | "Food"
  | "Crafting"
  | "Knowledge"
  | "Special";

export interface BuildingType {
  readonly id: string;
  readonly label: string;
  readonly category: Category;
  readonly description: string;
  readonly townhall?: boolean;
  /** Contributes villagers to the town's population. */
  readonly population?: boolean;
  /** Unlock ids that must be staffed before the plan can be crafted. */
  readonly requires?: readonly string[];
  /** Plan ingredients besides the wood plank. */
  readonly planExtra: readonly ItemId[];
  readonly jobs: readonly Job[];
}

